#!/usr/bin/env python3
"""Build the VerifiedRoot crypto and the board's policy table for the kernel link.

NioUfs authenticates every root window against an owner-signed policy bundle.
Three things are needed to link that code:

  * `vr_open`, `vr_verify_block` and `vr_xnu_crypto` -- the real implementation,
    from kits/VerifiedRoot. Nothing here substitutes for it.
  * `verified_root_policies` and `verified_root_policy_count` -- the signed
    policies for this board, declared by drivers/NioUfs/VerifiedBlockPolicy.h.
  * `verified_root_key` -- the trusted key, supplied independently of the
    untrusted envelope.

Only the second and third are board data, and this board does not have them yet.
They are signed over the exact root windows of the OS image that gets flashed,
so they cannot be derived offline and cannot be borrowed from another device.

So the table is generated empty. That is a truthful statement -- no policies are
configured -- not a stub that pretends to verify anything:
`NativeUfsBlock::configureVerification` rejects a zero policy count before it
reads the key or calls `vr_open`, so the driver runs with root verification
disabled and says so through gRootDiagnostic.stage. Replace the generated table
with the real bundle once one exists; nothing else has to change.

`boot_progress_poll` is defined here too. NativeUfs declares it weak and calls
it only from inside the verification path, so an observer that observes nothing
is the correct definition until a board diagnostic supplies a real one.

The result is a standalone archive. `[kernel]` builds it before the link and
`CONFIG_XNU_EXTRA_LD_ARCHIVES` puts it on the link line, where ld64 pulls the
member in to satisfy the driver's unresolved references.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'build/verified-root'
ARCHIVE = OUT / 'libVerifiedRoot.a'
CORE_OBJECTS = ROOT / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837'
BOOTSTRAP_OBJECTS = ROOT / 'build/xnu/obj/DEVELOPMENT_ARM64_BCM2837'
CORE_IMAGE = CORE_OBJECTS / 'mach.development.bcm2837.unstripped'
RECIPE = CORE_OBJECTS / 'osfmk/DEVELOPMENT/prng_random.o.json'

POLICY_SOURCE = '''/* SPDX-License-Identifier: BSD-2-Clause-Patent */
/* Generated by build-verified-root.py: this board has no signed policy bundle.
 * verified_root_policy_count == 0 makes NativeUfsBlock::configureVerification
 * return before it reads the key or calls vr_open, so root verification is
 * disabled rather than approximated. */
#include "verified_root.h"
#include "VerifiedBlockPolicy.h"

/* extern is required here: this compiles as C++, where a namespace-scope const
 * has internal linkage without it, and NativeUfs references the key by name. */
extern const uint8_t verified_root_key[VR_KEY_BYTES] = {0};

/* {0, 0} rather than {nullptr, 0}: the kernel's own compile record for this
 * recipe is a C record (-x c), so the generated table is C even though
 * VerifiedBlockPolicy.h is written to be usable from both. */
const NativeVerifiedBlockPolicy verified_root_policies[1] = {
    {0, 0},
};

const uint64_t verified_root_policy_count = 0;
'''

BOOT_PROGRESS_SOURCE = '''/* SPDX-License-Identifier: BSD-2-Clause-Patent */
/* Generated by build-verified-root.py. NativeUfs declares this weak and calls
 * it only while verifying a root window; an observer that observes nothing is
 * the right definition until a board diagnostic supplies a real one. */
void boot_progress_poll (void)
{
}
'''


def fail(message: str) -> None:
    raise SystemExit('build-verified-root: ' + message)


def compile_environment(tree: Path) -> dict[str, str]:
    """The environment kernel.py gives the archive builders, so the clang shim resolves."""
    import os
    import platform
    if platform.system() != 'Linux':
        return dict(os.environ)
    toolchain = Path(os.environ.get('UNIXNU_TOOLCHAIN', '/opt/unixnu-linux'))
    clt = toolchain / 'CommandLineTools/usr'
    xctoolchain = toolchain / 'XcodeDefault.xctoolchain/usr'
    fakeroot = tree / '.cache/fakeroot'
    env = dict(os.environ)
    env.update({
        'PATH': os.pathsep.join([str(clt / 'bin'), str(toolchain / 'bin'), os.environ.get('PATH', '')]),
        'LC_ALL': 'C',
        'CLT_PREFIX': str(clt),
        'XCTOOLCHAIN_PREFIX': str(xctoolchain),
        'XNU_TOOLCHAIN_BIN': f'{clt / "bin"} {xctoolchain / "bin"}',
        'UNIXNU_SDKROOT': str(fakeroot),
        'UNIXNU_SDK_VERSION': '17.0',
        'UNIXNU_PLATFORM_PATH': str(fakeroot / 'Platforms/iPhoneOS.platform'),
        'CROSS_CLANG': str(toolchain / 'llvm/bin/clang'),
        'DARWIN_TRIPLE': 'arm64-apple-ios17.0',
        'CROSS_EXTRA_FLAGS': '-mllvm -disable-atexit-based-global-dtor-lowering',
        'CCC_OVERRIDE_OPTIONS': '# +-Wno-missing-designated-field-initializers +-Wno-unused-but-set-global',
    })
    return env


def command_for(record: dict, source: Path, destination: Path, includes: list[Path]) -> list[str]:
    """The kernel's own compile flags, with the input and output swapped in."""
    command, index = [], 0
    arguments = record['arguments']
    while index < len(arguments):
        value = arguments[index]
        if value == record['file']:
            command.append(str(source))
        elif value == '-o':
            command += ['-o', str(destination)]
            index += 1
        elif value == '-Xclang' and index + 1 < len(arguments) and arguments[index + 1].startswith('-W'):
            index += 1
        elif not value.startswith('-W'):
            command.append(value)
        index += 1
    if '-o' not in command:
        command += ['-o', str(destination)]
    for include in includes:
        command += ['-I', str(include)]
    command += ['-Wno-error']
    return command


def force_core_rebuild() -> None:
    """Make the link read the patched sources instead of the core the tree ships.

    Run 549's own diagnostics say it plainly.  The published core carries none
    of that round's strings; `iokit/DEVELOPMENT/IOService.o` does not exist at
    all; and the prelink input has the mtime of the bootstrap pass, which
    failed at the link.  The tree therefore ships a
    `mach.development.bcm2837.unstripped` that is newer than every source, so
    make calls the core current and compiles nothing.  Every XNU patch of the
    last rounds was applied to a tree whose core was never rebuilt, and the
    phone has been running the same kernel, which is what "no change" on the
    panel has meant.

    Deleting the core image and the objects under it was the first attempt, and
    two rounds said it is not enough.  Run 550 removed 977 objects and the link
    came back in three minutes; run 551 went further, gave 115 patched sources a
    fresh mtime, spent 331 seconds in the final make, linked -- and still
    published a core with none of the series' strings in it, while its own log
    showed `bsd/kern/bsd_init.c` carrying `nio: bsd_init:` at the time.

    The reason is in MakeInc.kernel: the kernel's only per-component
    prerequisites are the `<component>.filelist` files, and those lists are what
    the link reads.  An object that is deleted but still named by a list that
    exists is simply not asked for.  So the lists are deleted here as well, with
    the component archives and the link's own outputs.  Without them make has to
    descend into every component, compile `$(OBJS)` from the sources the series
    changed, regenerate the lists and link a core that carries them.

    The compile records (`*.o.json`) are kept: this recipe read one of them,
    and they are what the archive builders were given.  `EXPORT_HDRS` stays too;
    the headers under it are restored from a blob by an earlier step.

    Only the CI does this.  A local tree carries a core that was built on
    purpose, and deleting it would make every local run of this recipe a full
    kernel rebuild.
    """
    if os.environ.get('GITHUB_ACTIONS') != 'true':
        return
    if not CORE_OBJECTS.is_dir():
        return

    # Two object roots exist.  The bootstrap pass compiles into build/xnu/obj,
    # the final pass into build/xnu/ios-obj, and the file lists the link reads
    # are written next to the objects they name.  The core of run 552 carried
    # the osfmk patch of that round and none of the bsd or iokit ones, while
    # its own log showed bsd/kern/bsd_init.c carrying the mark: the objects
    # that the link read were built earlier, from an older tree, out of the
    # other root.  So both roots are cleared.
    doomed = []
    for root in (CORE_OBJECTS, BOOTSTRAP_OBJECTS):
        if not root.is_dir():
            continue
        objects = list(root.rglob('*.o'))
        cpos = list(root.rglob('*.cpo'))
        archives = list(root.rglob('*.a'))
        filelists = (list(root.rglob('*.filelist'))
                     + list(root.rglob('*.libfilelist')))
        core = f'{CORE_IMAGE.stat().st_size} bytes' if CORE_IMAGE.exists() else 'absent'
        print(f'PASS: {root.name} holds {len(objects)} .o, {len(cpos)} .cpo, '
              f'{len(archives)} archives, {len(filelists)} file lists, core {core}')
        doomed += [CORE_IMAGE, *objects, *cpos, *archives, *filelists]
        for name in ('link.filelist', 'ltolink.filelist', 'nonltolink.filelist',
                     'mach.development.bcm2837', 'mach.development.bcm2837.dSYM',
                     '.LDFLAGS'):
            doomed.append(root / name)
    gone = 0
    for path in doomed:
        if path.is_dir():
            shutil.rmtree(path, ignore_errors=True)
            gone += 1
        elif path.is_file():
            path.unlink()
            gone += 1
    print(f'PASS: removed the core image, the file lists and {gone} build products')

    # Deleting the objects is not enough on its own: run 550 removed 977 of them
    # and the link still came back in three minutes with the tree's code in it,
    # so the objects a recipe reads are not all under this directory.  A source
    # with a fresh mtime cannot be skipped, whichever directory the object is
    # in -- make compares the two times, and "now" is later than any file the
    # tree shipped.  The series leaves its files modified in the work tree, so
    # git names them; nothing has to know which patch touched which file.
    touched, missing = touch_patched_sources()
    print(f'PASS: {touched} patched sources carry a fresh mtime'
          + (f' ({missing} named by git but not on disk)' if missing else ''))

    # A fresh mtime alone did not make make recompile kern_exec.c: rounds
    # 698-703 showed the source carrying every exec mark (UB01, D01..D13,
    # M02..) while kern_exec.o kept a constant 402872-byte body with only
    # D06/C02, and the published core inherited that stale object.  The
    # object's mtime was newer than the source's, so make called it current.
    # Change the CONTENT by appending a comment carrying this round's
    # identity: a C comment cannot affect codegen, but the new bytes (and a
    # fresh inode from writing via a temp file) force every content-based
    # dependency to rebuild the object from this exact source.
    work = ROOT / '.cache/xnu-work'
    token = os.environ.get('GITHUB_RUN_NUMBER', os.environ.get('GITHUB_RUN_ID', 'local'))
    for relative in ('bsd/kern/kern_exec.c',):
        path = work / relative
        if not path.is_file():
            print(f'  content-token: {relative} absent')
            continue
        raw = path.read_bytes()
        marker = f'/* nio rebuild token {token} */\n'.encode()
        if marker in raw:
            continue
        import hashlib as _h
        print(f'  content-token {relative}: {_h.sha256(raw).hexdigest()[:16]} ', end='')
        tmp = path.with_name(path.name + '.niotmp')
        tmp.write_bytes(raw + b'\n' + marker)
        os.replace(tmp, path)   # new inode: defeats any hard link to a cached copy
        print('-> ' + _h.sha256(path.read_bytes()).hexdigest()[:16])
    for relative, mark in (('bsd/kern/bsd_init.c', b'nio: bsd_init: '),
                           ('iokit/Kernel/IOService.cpp', b'nio: S1'),
                           ('bsd/kern/kern_exec.c', b'nio: exec: load_init_program enter')):
        path = ROOT / '.cache/xnu-work' / relative
        if not path.is_file():
            print(f'  {relative}: absent')
            continue
        raw = path.read_bytes()
        stamp = time.strftime('%H:%M:%S', time.localtime(path.stat().st_mtime))
        print(f'  {relative}: mtime {stamp}, '
              + ('carries ' if mark in raw else 'does NOT carry ')
              + repr(mark.decode().strip()))


def touch_patched_sources() -> tuple[int, int]:
    """Give every file the series changed a mtime of now, so make cannot skip it.

    Two sources name them.  The work tree is a git clone and `git apply` leaves
    the patches unstaged, so its status is the full list; the series' own
    `+++ b/` lines are read as well, because a tree that arrived with the
    patches committed would report nothing.  A path that is not on disk is
    skipped -- a patch may delete one.
    """
    work = ROOT / '.cache/xnu-work'
    if not work.is_dir():
        return 0, 0
    names: list[str] = []
    if (work / '.git').exists():
        listed = subprocess.run(['git', '-C', str(work), 'status', '--porcelain'],
                                capture_output=True, text=True, check=False)
        for line in listed.stdout.splitlines():
            relative = line[3:].strip()
            if ' -> ' in relative:
                relative = relative.split(' -> ', 1)[1]
            names.append(relative.strip('"'))
    for directory in (ROOT / 'patches/xnu', ROOT / 'patches/xnu-8796'):
        for patch in sorted(directory.glob('*.patch')):
            for line in patch.read_text(errors='replace').splitlines():
                if line.startswith('+++ b/'):
                    names.append(line[6:].strip())
    touched = missing = 0
    for relative in dict.fromkeys(names):
        path = work / relative
        if path.is_file():
            os.utime(path, None)
            touched += 1
        else:
            missing += 1
    return touched, missing


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('sources', nargs='*',
                        help='ignored; kept so board.toml entries stay uniform')
    parser.add_argument('--archive', type=Path, default=ARCHIVE, help='archive to write')
    args = parser.parse_args()
    del args.sources

    if not RECIPE.is_file():
        fail(f'missing {RECIPE}; run "unixnu build kernel" once to record the compiles')
    record = json.loads(RECIPE.read_text().strip().rstrip(','))
    OUT.mkdir(parents=True, exist_ok=True)

    includes = [ROOT / 'kits/VerifiedRoot/include',
                ROOT / 'drivers/NioUfs',
                ROOT / '.cache/xnu-work/osfmk']
    kit = ROOT / 'kits/VerifiedRoot'
    # VerifiedBlockPolicy.h is a C++ header -- it uses extern "C", static_assert
    # and nullptr -- so the generated table is C++ even though it defines
    # C-linkage objects.
    generated = OUT / 'verified-root-policies.cpp'
    generated.write_text(POLICY_SOURCE)
    boot = OUT / 'boot-progress-stub.c'
    boot.write_text(BOOT_PROGRESS_SOURCE)

    objects = []
    for source in (kit / 'src/verified_root.c', kit / 'adapters/xnu_crypto.c', generated, boot):
        if not source.is_file():
            fail(f'missing {source}')
        destination = OUT / (source.stem + '.o')
        command = command_for(record, source, destination, includes)
        (OUT / f'{source.stem}.compile-command.json').write_text(json.dumps(command, indent=2) + '\n')
        result = subprocess.run(command, cwd=record['directory'], env=compile_environment(ROOT),
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        (OUT / f'{source.stem}.compile.log').write_text(result.stdout or '')
        if result.returncode:
            fail(f'{source.name} did not compile:\n' + (result.stdout or '')[-3000:])
        objects.append(destination)

    args.archive.parent.mkdir(parents=True, exist_ok=True)
    args.archive.unlink(missing_ok=True)
    result = subprocess.run(['xcrun', 'ar', 'rcs', str(args.archive), *map(str, objects)],
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if result.returncode:
        fail('xcrun ar failed: ' + (result.stdout or ''))

    # cctools nm has no --defined-only, so list everything and drop the
    # undefined rows: "                 U _name" against "0000000000000000 T _name".
    listing = subprocess.run(['xcrun', 'nm', '-g', str(args.archive)],
                             stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    (OUT / 'nm.txt').write_text(listing.stdout or '')
    defined = {parts[2] for line in (listing.stdout or '').splitlines()
               if len(parts := line.split()) == 3 and parts[1] != 'U'}
    needed = {'_vr_open', '_vr_verify_block', '_vr_xnu_crypto',
              '_verified_root_key', '_verified_root_policies', '_verified_root_policy_count',
              '_boot_progress_poll'}
    missing = sorted(needed - defined)
    if missing:
        fail('these symbols are still missing from the archive: ' + ', '.join(missing))

    (OUT / 'report.json').write_text(json.dumps({
        'sources': ['kits/VerifiedRoot/src/verified_root.c', 'kits/VerifiedRoot/adapters/xnu_crypto.c',
                    'generated verified-root-policies.cpp', 'generated boot-progress-stub.c'],
        'verified_root_policy_count': 0,
        'root_verification': 'disabled: this board has no signed policy bundle',
        'boot_progress_poll': 'no-op observer',
        'archive': str(args.archive),
        'original_code_modified': False,
    }, indent=2) + '\n')
    print('PASS: real VerifiedRoot crypto + empty policy table -> ' + args.archive.name)
    print('      root verification is disabled: no signed policy bundle exists for this board')
    force_core_rebuild()
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
