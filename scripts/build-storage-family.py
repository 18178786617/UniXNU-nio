#!/usr/bin/env python3
"""Compile Apple's IOStorageFamily into the kernel link as a static archive.

Why this exists
---------------
drivers/NioUfs publishes the boot volumes through a class that derives from
IOBlockStorageDevice:

    class NioUfsBlock : public IOBlockStorageDevice   (NioUfs.cpp:1474)

On iOS that base class is not in the kernel.  IOStorageFamily is a kext, and
on a stock phone the kernel is a prelinked kernelcache that already carries
it.  This board builds a standalone kernel.macho out of XNU and force-loads
the board's own archives into it, so nothing on the link line defines
IOBlockStorageDevice and run 35 ended exactly there:

    "vtable for IOBlockStorageDevice", referenced from:
        vtable for NioUfsBlock in libShengUfs.a[2](NioUfs.o)
    ld: symbol(s) not found for architecture arm64

Building the family from source is the answer this repository already uses
for HID and for its own UFS transport: compile Apple's compilation units
against the kernel's own compile record, archive them, and let the kernel
link carry them.  The list below is the PBXSourcesBuildPhase of Apple's
IOStorageFamily kernel target, from the same pinned checkout
prepare-storage-headers.py takes its public headers from
(refer/IOStorageFamily, commit e45fbe30a7879e0b16e26dddb78538f1b00e0bff).

Two files from upstream's target are handled differently:

  IOStorageFeatures.cpp            does not exist in this checkout
  IOUserBlockStorageDevice_kext.cpp
                                   is not compiled. It is the DriverKit-backed
                                   subclass, and the header it needs is
                                   generated by `xcrun iig` from
                                   BlockStorageDeviceDriverKit/
                                   IOUserBlockStorageDevice.iig. That
                                   generation still runs here, because
                                   IOBlockStorageDriver.cpp includes
                                   IOUserBlockStorageDevice_kext.h and
                                   OSDynamicCasts a provider to that class --
                                   a cast needs the class object -- so the
                                   generated implementation is compiled and
                                   archived with the rest.

How the objects are built
-------------------------
The command is not chosen here.  scripts/build-arm-driver.py established the
pattern this board uses: replay the kernel's own compile record
(iookit/DEVELOPMENT/IOPlatformExpert.cpo.json, added to the tree by
xnu-8796-compile-records.patch and therefore present before the archives
stage runs), swapping only the input, the output and the warning flags.  That
is what makes the objects ABI-compatible with the kernel they are linked
into -- the same -fapple-kext, the same PAC settings, the same sanitizer
runtime, the same deployment target.

Two things are added to that record:

  -I refer/IOStorageFamily          the family's own headers ("IOStorage.h"
                                    style includes, not <IOKit/storage/...>)
  -I build/storage-abi/include      the public <IOKit/storage/...> header set
                                    prepare-storage-headers.py just built

and every -W option is removed, replaced with -Wno-error.  These are Apple's
sources, not this board's: a warning that the kernel's own -Werror would turn
into a failure here is reported in the log and not acted on.  The loop
compiles every file before failing, so one run reports every error instead of
only the first.

The archive is force-loaded by the kernel link through
CONFIG_XNU_EXTRA_LD_ARCHIVES in configs/nio_defconfig.  Force-load, not a
plain archive argument: IOMedia, the partition schemes and the storage driver
are reached through the class registry at run time, not through a reference
in another object, and a plain archive would leave them out.
"""
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Apple's IOStorageFamily kernel target, in the order upstream builds it.
# IOUserBlockStorageDevice_kext.cpp is not here: it is the DriverKit-backed
# subclass and is replaced below by the implementation `xcrun iig` generates
# from its .iig definition, which is what upstream's target compiles too.
FAMILY = [
    'IOAppleLabelScheme',
    'IOApplePartitionScheme',
    'IOBlockStorageDevice',
    'IOBlockStorageDriver',
    'IOFDiskPartitionScheme',
    'IOFilterScheme',
    'IOGUIDPartitionScheme',
    'IOMedia',
    'IOMediaBSDClient',
    'IOPartitionScheme',
    'IORequest',
    'IORequestsPool',
    'IOStorage',
]


def switch(name):
    """A CONFIG_ value as 0 or 1 (kernel.py exports =n as "0" and =y as "1")."""
    value = os.environ.get(name, '1').strip().strip('"').lower()
    if value in ('1', 'y', 'yes', 'true', 'on'):
        return '1'
    if value in ('0', 'n', 'no', 'false', 'off', ''):
        return '0'
    sys.exit('%s must be 0 or 1, not %r' % (name, value))


if switch('XNU_NATIVE_IOSTORAGE') != '1':
    print('storage-family: CONFIG_XNU_NATIVE_IOSTORAGE is off; nothing compiled')
    raise SystemExit(0)

source_dir = (ROOT / 'refer/IOStorageFamily').resolve()
missing = [name for name in FAMILY if not (source_dir / (name + '.cpp')).is_file()]
if missing:
    sys.exit('refer/IOStorageFamily does not carry: %s\n'
             'run "unixnu tree" so the pinned checkout is present' % ', '.join(missing))

recipe = ROOT / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/iokit/DEVELOPMENT/IOPlatformExpert.cpo.json'
if not recipe.is_file():
    sys.exit('the kernel compile record is missing: %s\n'
             'xnu-8796-compile-records.patch adds it, and the bootstrap pass generates it'
             % recipe)
record = json.loads(recipe.read_text().strip().rstrip(','))
arguments = record['arguments']

out = ROOT / 'build/storage-family'
out.mkdir(parents=True, exist_ok=True)
program = arguments[0]


def command_for(source, destination, extra=()):
    """The kernel's compile line with this source, this output and no -W options."""
    command = [program]
    index = 1
    # arguments[1] is the record's own input file (the -xc++ before it stays).
    consumed_input = False
    while index < len(arguments):
        value = arguments[index]
        if value == record['file']:
            command.append(str(source))
            consumed_input = True
        elif value == '-o':
            command.extend(['-o', str(destination)])
            index += 1
        elif value == '-Xclang' and index + 1 < len(arguments) and arguments[index + 1].startswith('-W'):
            index += 1
        elif not value.startswith('-W'):
            command.append(value)
        index += 1
    if not consumed_input:
        sys.exit('the compile record does not name its own input: %s' % record['file'])
    command.extend(['-Wno-error',
                    # IOMediaBSDClient.cpp still declares two locals `register`.
                    # C++17 removed the keyword and clang reports it as an error
                    # by default, so -Wno-error alone does not cover it; the two
                    # lines are Apple's, from 2015, and mean nothing on arm64.
                    '-Wno-register',
                    '-Wno-deprecated-declarations',
                    '-I', str(source_dir),
                    '-I', str(ROOT / 'build/storage-abi/include'),
                    *extra])
    return command


def generate_user_block_device():
    """Generate IOUserBlockStorageDevice.h with `xcrun iig`, as upstream's target does.

    IOBlockStorageDriver.cpp includes IOUserBlockStorageDevice_kext.h, which
    includes the generated header and dynamic_casts a provider to that class.
    A cast needs the class object, so the generated implementation is compiled
    and archived with the rest -- a forward declaration would leave
    IOUserBlockStorageDevice::metaClass undefined at the kernel link.
    """
    definition = source_dir / 'BlockStorageDeviceDriverKit/IOUserBlockStorageDevice.iig'
    if not definition.is_file():
        sys.exit('%s is missing; the checkout is not the pinned IOStorageFamily' % definition)
    generated = out / 'generated'
    generated.mkdir(exist_ok=True)
    header, implementation = generated / 'IOUserBlockStorageDevice.h', generated / 'IOUserBlockStorageDevice.iig.cpp'
    driver_sdk = Path(subprocess.check_output(
        ['xcrun', '--sdk', 'driverkit', '--show-sdk-path'], text=True).strip())
    command = ['xcrun', 'iig', '--def', str(definition), '--header', str(header),
               '--impl', str(implementation), '--', '-x', 'c++', '-std=gnu++17',
               '-fno-exceptions', '-fno-rtti', '-D__IIG=1', '-DPLATFORM_DriverKit=1',
               '-isysroot', str(driver_sdk), '-iframework',
               str(driver_sdk / 'System/DriverKit/System/Library/Frameworks'),
               '-idirafter', str(driver_sdk / 'System/DriverKit/usr/include')]
    (generated / 'command.json').write_text(json.dumps(command, indent=2) + '\n')
    result = subprocess.run(command, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    (generated / 'generate.log').write_text(result.stdout)
    if result.returncode:
        sys.exit('xcrun iig failed:\n' + result.stdout[-3000:])
    if not header.is_file() or not implementation.is_file():
        sys.exit('xcrun iig reported success but wrote no header or implementation')
    print('PASS iig generated %s (%d bytes) and its implementation (%d bytes)'
          % (header.name, header.stat().st_size, implementation.stat().st_size))
    return generated, implementation


generated, iig_implementation = generate_user_block_device()
iig_flags = ['-I', str(generated)]

objects = []
failures = []
work = [(name, source_dir / (name + '.cpp')) for name in FAMILY]
work.append(('IOUserBlockStorageDevice.iig', iig_implementation))
for name, source in work:
    destination = out / (Path(name).stem + '.o')
    destination.unlink(missing_ok=True)
    command = command_for(source, destination, iig_flags)
    (out / (name + '.command.json')).write_text(json.dumps(command, indent=2) + '\n')
    result = subprocess.run(command, cwd=record['directory'], text=True,
                           stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    (out / (name + '.log')).write_text(result.stdout)
    if result.returncode:
        errors = [line for line in result.stdout.splitlines() if 'error:' in line]
        failures.append((name, errors or result.stdout.splitlines()[-6:]))
        print('FAIL %s (%d lines of log, %d errors)' % (name, len(result.stdout.splitlines()), len(errors)))
        continue
    objects.append(destination)
    warnings = sum('warning:' in line for line in result.stdout.splitlines())
    print('PASS %s (%d warnings)' % (name, warnings))

if failures:
    print()
    for name, lines in failures:
        print('--- %s ---' % name)
        for line in lines[:12]:
            print('   ', line.strip())
    print()
    sys.exit('%d of %d IOStorageFamily sources did not compile; full logs in %s'
             % (len(failures), len(work), out))

archive = out / 'libIOStorageFamily.a'
archive.unlink(missing_ok=True)
subprocess.run(['xcrun', 'ar', 'rcs', str(archive), *map(str, objects)], check=True)

# The kernel link force-loads this archive, so it has to carry the class
# objects and not just the compiled code. Two things are read off nm here:
#
#   - that the archive has C++ definitions at all, which is fatal if false,
#     because an empty archive links cleanly and puts the failure somewhere
#     else entirely;
#   - which classes have a vtable or metaclass, as a note only. The link is
#     the authority, and it names a missing vtable in one line. Runs 37 and
#     38 both died in this block instead -- the parse read field 2 as the
#     symbol name, which in POSIX format is the value, so every class looked
#     absent while all fourteen objects had in fact compiled. The fields are
#     now found by shape, not by position.
table = subprocess.run(['xcrun', 'nm', '-gP', str(archive)], text=True,
                       stdout=subprocess.PIPE, check=True).stdout
defined = set()
for line in table.splitlines():
    parts = line.split()
    if not parts:
        continue
    symbol = next((part for part in parts if part.startswith('_Z')), None)
    kind = next((part for part in parts if len(part) == 1 and part.isalpha()), None)
    if symbol and kind in 'TSDBRC':
        defined.add(symbol)
required = ['IOBlockStorageDevice', 'IOMedia', 'IOBlockStorageDriver', 'IOGUIDPartitionScheme',
            'IOApplePartitionScheme', 'IOFDiskPartitionScheme', 'IOMediaBSDClient']
absent = [name for name in required
          if not any(symbol.endswith('ZTV%d%s' % (len(name), name)) for symbol in defined)
          and not any(symbol.endswith('ZN%d%s9metaClassE' % (len(name), name)) for symbol in defined)]
if not defined:
    sys.exit('the archive defines no C++ symbols at all; %d objects, %d bytes'
             % (len(objects), archive.stat().st_size))
if absent:
    # Not fatal. The kernel link is the authority on whether a class is
    # missing, and it names the missing vtable in one line. This check has
    # already been wrong twice for reasons that had nothing to do with the
    # archive, and a diagnostic must not be the thing that stops a build.
    print('NOTE: nm shows no vtable or metaclass for: %s' % ', '.join(absent))
print('PASS: %d objects, %d defined symbols, %d bytes -> %s'
      % (len(objects), len(defined), archive.stat().st_size, archive.relative_to(ROOT)))
